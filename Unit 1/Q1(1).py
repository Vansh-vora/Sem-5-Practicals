#Create a Python program that will have 3 variables which stores integer, float and
#complex value. Display its value and also demonstrate its datatype class using type().

int_var=2
float_var=2.5
complex_var=2+3j

print("Integer Variable:",int_var)
print("Type of Integer Variable:", type(int_var))

print("Float Variable:", float_var)
print("Type of float Variable:", type(float_var))

print("Comlex Variable:", complex_var)
print("Type of Complex Variable:", type(complex_var))
